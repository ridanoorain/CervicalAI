import json
import random
from pathlib import Path
from collections import Counter


# ============================================================
# CONFIGURATION
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[2]

METADATA_PATH = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "cell_crops_metadata.json"
)

OUTPUT_DIR = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "splits"
)

TRAIN_RATIO = 0.70
VAL_RATIO = 0.15
TEST_RATIO = 0.15

RANDOM_SEED = 42


# ============================================================
# LOAD METADATA
# ============================================================

def load_metadata():

    print("=" * 70)
    print("RIVA DATASET PREPARATION")
    print("=" * 70)

    print("\nLoading metadata from:")
    print(METADATA_PATH)

    if not METADATA_PATH.exists():
        raise FileNotFoundError(
            f"Metadata file not found:\n{METADATA_PATH}"
        )

    with open(METADATA_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    print("Successfully loaded metadata.")

    return data


# ============================================================
# EXTRACT SAMPLES
# ============================================================

def extract_samples(data):

    samples = []

    # The metadata generated by create_cell_crops.py
    # may be stored either as a list or dictionary.
    #
    # We handle both formats.

    if isinstance(data, list):

        raw_samples = data

    elif isinstance(data, dict):

        # If metadata contains a top-level "samples" field
        if "samples" in data:
            raw_samples = data["samples"]

        # Otherwise assume image IDs are the keys
        else:
            raw_samples = []

            for image_id, image_data in data.items():

                if not isinstance(image_data, list):
                    continue

                for item in image_data:

                    if isinstance(item, dict):

                        item = item.copy()
                        item.setdefault("image_id", image_id)

                        raw_samples.append(item)

    else:

        raise ValueError(
            "Unexpected metadata format."
        )

    for item in raw_samples:

        if not isinstance(item, dict):
            continue

        image_id = (
            item.get("image_id")
            or item.get("image")
            or item.get("cell_id")
        )

        crop_path = (
            item.get("crop_path")
            or item.get("crop")
            or item.get("filename")
        )

        soft_label = (
            item.get("soft_label")
            or item.get("soft_labels")
        )

        if image_id is None:
            continue

        if crop_path is None:
            continue

        if soft_label is None:
            continue

        sample = {
            "image_id": image_id,
            "crop_path": crop_path,
            "soft_label": soft_label,
        }

        # Preserve useful information if available
        if "x" in item:
            sample["x"] = item["x"]

        if "y" in item:
            sample["y"] = item["y"]

        if "expert_labels" in item:
            sample["expert_labels"] = item["expert_labels"]

        if "reference_index" in item:
            sample["reference_index"] = item["reference_index"]

        samples.append(sample)

    return samples


# ============================================================
# VERIFY SAMPLES
# ============================================================

def verify_samples(samples):

    print("\n" + "=" * 70)
    print("DATASET VERIFICATION")
    print("=" * 70)

    print(f"\nTotal samples found: {len(samples)}")

    if len(samples) == 0:
        raise ValueError(
            "No samples found in cell_crops_metadata.json"
        )

    missing_crops = []

    for sample in samples:

        crop_path = Path(sample["crop_path"])

        # Handle relative paths
        if not crop_path.is_absolute():
            crop_path = PROJECT_ROOT / crop_path

        if not crop_path.exists():
            missing_crops.append(str(crop_path))

    print(f"Missing crop files: {len(missing_crops)}")

    if missing_crops:

        print("\nFirst missing files:")

        for path in missing_crops[:10]:
            print(path)

        raise FileNotFoundError(
            "Some crop files referenced in metadata are missing."
        )

    print("All crop files exist.")


# ============================================================
# GROUP BY ORIGINAL IMAGE
# ============================================================

def group_by_image(samples):

    groups = {}

    for sample in samples:

        image_id = sample["image_id"]

        if image_id not in groups:
            groups[image_id] = []

        groups[image_id].append(sample)

    return groups


# ============================================================
# CREATE TRAIN / VAL / TEST SPLIT
# ============================================================

def create_splits(groups):

    image_ids = list(groups.keys())

    random.seed(RANDOM_SEED)

    random.shuffle(image_ids)

    total_images = len(image_ids)

    train_count = int(total_images * TRAIN_RATIO)
    val_count = int(total_images * VAL_RATIO)

    train_ids = image_ids[:train_count]

    val_ids = image_ids[
        train_count:
        train_count + val_count
    ]

    test_ids = image_ids[
        train_count + val_count:
    ]

    train_samples = []

    for image_id in train_ids:
        train_samples.extend(groups[image_id])

    val_samples = []

    for image_id in val_ids:
        val_samples.extend(groups[image_id])

    test_samples = []

    for image_id in test_ids:
        test_samples.extend(groups[image_id])

    return (
        train_ids,
        val_ids,
        test_ids,
        train_samples,
        val_samples,
        test_samples,
    )


# ============================================================
# GET MAJORITY LABEL
# ============================================================

def get_majority_label(soft_label):

    if not soft_label:
        return None

    return max(
        soft_label,
        key=soft_label.get
    )


# ============================================================
# PRINT SPLIT INFORMATION
# ============================================================

def print_split_info(
    name,
    image_ids,
    samples
):

    print("\n" + "-" * 70)
    print(f"{name.upper()} SET")
    print("-" * 70)

    print(f"Images : {len(image_ids)}")
    print(f"Cells  : {len(samples)}")

    label_counts = Counter()

    for sample in samples:

        label = get_majority_label(
            sample["soft_label"]
        )

        if label:
            label_counts[label] += 1

    print("\nMajority-label distribution:")

    for label, count in label_counts.most_common():

        percentage = (
            count / len(samples) * 100
            if samples
            else 0
        )

        print(
            f"{label:<8}: "
            f"{count:5d} "
            f"({percentage:6.2f}%)"
        )


# ============================================================
# SAVE SPLIT
# ============================================================

def save_split(
    name,
    image_ids,
    samples
):

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    output = {
        "split": name,
        "random_seed": RANDOM_SEED,
        "num_images": len(image_ids),
        "num_cells": len(samples),
        "image_ids": image_ids,
        "samples": samples,
    }

    output_path = OUTPUT_DIR / f"{name}.json"

    with open(
        output_path,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            output,
            f,
            indent=2
        )

    print(
        f"\nSaved {name} split to:"
        f"\n{output_path}"
    )


# ============================================================
# CHECK FOR DATA LEAKAGE
# ============================================================

def check_leakage(
    train_ids,
    val_ids,
    test_ids
):

    train_set = set(train_ids)
    val_set = set(val_ids)
    test_set = set(test_ids)

    train_val = train_set & val_set
    train_test = train_set & test_set
    val_test = val_set & test_set

    print("\n" + "=" * 70)
    print("DATA LEAKAGE CHECK")
    print("=" * 70)

    print(
        f"\nTrain ∩ Validation : {len(train_val)}"
    )

    print(
        f"Train ∩ Test       : {len(train_test)}"
    )

    print(
        f"Validation ∩ Test  : {len(val_test)}"
    )

    if train_val or train_test or val_test:

        raise RuntimeError(
            "DATA LEAKAGE DETECTED!"
        )

    print("\nNo image-level data leakage detected.")


# ============================================================
# MAIN
# ============================================================

def main():

    data = load_metadata()

    samples = extract_samples(data)

    verify_samples(samples)

    groups = group_by_image(samples)

    print("\n" + "=" * 70)
    print("GROUPING")
    print("=" * 70)

    print(
        f"\nUnique original images: {len(groups)}"
    )

    (
        train_ids,
        val_ids,
        test_ids,
        train_samples,
        val_samples,
        test_samples,
    ) = create_splits(groups)

    # --------------------------------------------------------
    # PRINT SPLIT INFORMATION
    # --------------------------------------------------------

    print_split_info(
        "train",
        train_ids,
        train_samples
    )

    print_split_info(
        "validation",
        val_ids,
        val_samples
    )

    print_split_info(
        "test",
        test_ids,
        test_samples
    )

    # --------------------------------------------------------
    # LEAKAGE CHECK
    # --------------------------------------------------------

    check_leakage(
        train_ids,
        val_ids,
        test_ids
    )

    # --------------------------------------------------------
    # SAVE
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("SAVING DATASET SPLITS")
    print("=" * 70)

    save_split(
        "train",
        train_ids,
        train_samples
    )

    save_split(
        "val",
        val_ids,
        val_samples
    )

    save_split(
        "test",
        test_ids,
        test_samples
    )

    # --------------------------------------------------------
    # FINAL SUMMARY
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("DATASET PREPARATION COMPLETE")
    print("=" * 70)

    print("\nFinal dataset:")

    print(
        f"Train      : "
        f"{len(train_ids)} images, "
        f"{len(train_samples)} cells"
    )

    print(
        f"Validation : "
        f"{len(val_ids)} images, "
        f"{len(val_samples)} cells"
    )

    print(
        f"Test       : "
        f"{len(test_ids)} images, "
        f"{len(test_samples)} cells"
    )

    print(
        f"\nTotal      : "
        f"{len(groups)} images, "
        f"{len(samples)} cells"
    )

    print(
        f"\nSplits saved in:"
        f"\n{OUTPUT_DIR}"
    )


if __name__ == "__main__":
    main()